// in path order, so a creature's home (data/scaling.ts) is the earliest zone it lives in
export const BRANCH_STAGES: StageDef[] = [...BRANCH_DATA].sort((a, b) => a.index - b.index).map(({ index, ...st }) => ({
  ...st,
  scale: (STAGES[index - 1].scale * STAGES[index - 1].evolveSize) / st.startSize,
}));
const BRANCH_INDEX = new Map(BRANCH_DATA.map((b) => [b.id, b.index]));

/** Forms you can become at this stage index (one unless the path branches here). */
export const stageChoices = (index: number): StageDef[] =>
  STAGES[index] ? [STAGES[index], ...BRANCH_STAGES.filter((b) => BRANCH_INDEX.get(b.id) === index)] : [];

/** The stage index a form is played at (arenas and branches; finales are the last stage). */
export const stageIndexOf = (id: string): number => {
  const main = STAGES.findIndex((s) => s.id === id);
  return main >= 0 ? main : BRANCH_INDEX.get(id) ?? STAGES.length;
};

export const stageById = (id: string): StageDef | undefined => [...STAGES, ...BRANCH_STAGES, ...OVERLORDS].find((s) => s.id === id);

