/** Chains the stages into one continuous size scale: stage n starts as big as stage n-1 ended. */
function scaleStages(raw: Omit<StageDef, 'scale'>[]): StageDef[] {
  let k = 1;
  return raw.map((st, i) => {
    if (i > 0) k *= raw[i - 1].evolveSize / st.startSize;
    return { ...st, scale: k };
  });
}

