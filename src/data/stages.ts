import type { SignatureId } from './signatures';
import type { TraitId } from './traits';

export interface DecorDef {
  texture: string;
  count: number;
  scale: [number, number];
  alpha?: number;
}

export interface SpawnDef {
  creature: string;
  count: number;
  /** Spawn in packs/herds of this size. */
  group?: number;
}

export interface StageDef {
  id: string;
  /** What the player is in this stage. */
  creatureName: string;
  biome: string;
  intro: string;
  /** Shown on the metamorphosis screen when you arrive here. */
  arrival?: string;
  playerTexture: string;
  /** What only this creature form can do. */
  signature: SignatureId;
  startSize: number;
  /**
   * Size grows by area: newSize = sqrt(size^2 + growthRate * preySize^2). Tuned per stage so each
   * stage takes a similar amount of play time.
   */
  growthRate: number;
  /** DNA needed for the first trait pick in this stage (each later pick costs 25% more). */
  dnaBase: number;
  /** Reaching this size evolves you into the next stage. */
  evolveSize: number;
  /** Player speed at startSize (scales up as you grow). */
  baseSpeed: number;
  /** How quickly the player turns and accelerates (default 9; lower = wider turns). */
  accel?: number;
  /** Flying form: the dash goes farther (Aerial). */
  aerial?: boolean;
  /** The form this one evolves into by default, if not the main path's next stage. */
  next?: string;
  worldSize: number;
  /** Camera zoom at startSize (zooms out as you grow). */
  baseZoom: number;
  bgColor: number;
  groundTexture: string;
  decor: DecorDef[];
  spawns: SpawnDef[];
  /** Funny line for the game-over screen if you die here. */
  epitaph: string;
  /** Branching forms only: how this form plays, shown on the path choice. */
  pitch?: string;
  /** Traits this form makes the most of: offered more often while you are it, and marked on the card. */
  affinity?: TraitId[];
  /** Trait names that differ from the default form for this stage (e.g. no feathers on a croc). */
  traitForms?: Partial<Record<TraitId, string>>;
  /** Water pools (or kelp forests) you can dive into. Radius in world px. */
  pools?: { count: number; radius: [number, number]; style?: 'water' | 'kelp' };
  /** Submerge: inside a pool you are hidden and swim faster. */
  submerge?: boolean;
  /**
   * How big one unit of this stage is in "true" size. Each form starts exactly as big as the
   * previous form ended, so stage n's units are evolveSize(n-1) / startSize(n) times stage n-1's.
   * Each stage keeps its own units; creatures that return from an earlier stage are shrunk into
   * the current stage's units (see data/scaling.ts). Computed, not hand-written.
   */
  scale: number;
}

/** How a form moves on screen: insects buzz, birds glide, land animals walk, water forms swim. */
export type Motion = 'buzz' | 'glide' | 'walk' | 'swim';

const GLIDERS = ['swift', 'eagle', 'thunderbird', 'roc'];
const WALKERS = ['lizard', 'raptor', 'tyrant', 'apex'];

export const formMotion = (st: StageDef): Motion =>
  st.submerge ? 'swim' : GLIDERS.includes(st.playerTexture) ? 'glide' : WALKERS.includes(st.playerTexture) ? 'walk' : 'buzz';

